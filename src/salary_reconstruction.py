"""Read-only remuneration decomposition. No production salary contracts are enabled.

Trusted reviewed contracts bind to one complete extraction. Accounting completeness
is not contractual recurrence. No estimates, net-based salary or residual salary.
"""

from dataclasses import dataclass
from decimal import ROUND_HALF_UP, Decimal, localcontext
from enum import StrEnum

from src.breakdown_completeness import diagnose_breakdown
from src.canonical.serialization import canonical_sha256
from src.canonical.values import ExactDecimal, ValueState
from src.document_concepts import ExtractionConcepts, FactEvidence
from src.economic_classification import (
    ClassifiedConcept,
    Function,
    Knowledge,
    Nature,
    classify_extraction,
)
from src.salary_reconciliation import Diagnostic, Status

Month = tuple[int, int]


class Bucket(StrEnum):
    FIXED = "Fijo ordinario acreditado"
    FIXED_CANDIDATE = "Salario base/complemento identificado; fijo no acreditado"
    EXTRA = "Extra incluida"
    PRORATION = "Prorrata salarial identificada"
    VARIABLE = "Bonus / variable"
    ADJUSTMENT = "Atrasos y regularizaciones"
    OTHER = "Otras partidas identificadas"
    UNKNOWN = "Pendiente de clasificación funcional"


class Coverage(StrEnum):
    COMPLETE = "Cobertura completa acreditada"
    PARTIAL = "Cobertura parcial"
    UNAVAILABLE = "No determinable"


class PaymentMode(StrEnum):
    PRORATED = "12 mensualidades con extras prorrateadas acreditadas"
    SEPARATE = "Ordinarias y extras separadas acreditadas"
    OTHER = "Otra modalidad acreditada"
    DECLARED = "Modalidad declarada, no verificada"
    UNKNOWN = "Modalidad desconocida"


@dataclass(frozen=True)
class Scope:
    document_id: str
    version_id: str
    extraction_id: str
    extractor_name: str
    extractor_revision: str
    content_hash: str


def scope_for(e: ExtractionConcepts) -> Scope:
    return Scope(
        e.document_id,
        e.version_id,
        e.extraction_id,
        e.extractor_name,
        e.extractor_revision,
        e.content_hash,
    )


@dataclass(frozen=True)
class ContractEvidence:
    """Trusted caller's reviewed evidence, never generated by numerical matching.

    Reference must identify an independently reviewed remuneration agreement or
    explicit documentary guarantee. A hash binds content, not economic truth.
    Period is documentary context, not an inferred payment/accrual date.
    """

    scope: Scope
    reference: str
    period: Month
    contract_version: str = "remuneration/b2b2-v1"


@dataclass(frozen=True)
class FixedContract:
    evidence: ContractEvidence
    occurrences: tuple[str, ...]
    complete: bool = False
    full_month: bool = False
    common_unit: bool = False
    signed_amounts: bool = False


@dataclass(frozen=True)
class PaymentContract:
    evidence: ContractEvidence
    mode: PaymentMode
    accredited: bool = False


@dataclass(frozen=True)
class AnnualTerm:
    occurrence: str
    repetitions: int


@dataclass(frozen=True)
class AnnualContract:
    evidence: ContractEvidence
    terms: tuple[AnnualTerm, ...]
    valid_from: Month
    valid_until: Month
    full_extra_composition: bool = False


@dataclass(frozen=True)
class ExactAmount:
    """Exact Decimal numerator / integer divisor; no rounded economic quotient."""

    numerator: Decimal
    divisor: int = 1

    def __post_init__(self) -> None:
        if not self.numerator.is_finite() or type(self.divisor) is not int or self.divisor < 1:
            raise ValueError("Finite decimal and positive integer divisor required")

    def display(self) -> str:
        with localcontext() as ctx:
            ctx.prec = max(
                32,
                len(self.numerator.as_tuple().digits)
                + abs(int(self.numerator.as_tuple().exponent))
                + 10,
            )
            rounded = (self.numerator / self.divisor).quantize(
                Decimal(".01"), rounding=ROUND_HALF_UP
            )
            return format(rounded, ",.2f").replace(",", "_").replace(".", ",").replace("_", ".")


@dataclass(frozen=True)
class Part:
    source: ClassifiedConcept
    bucket: Bucket
    amount: Decimal | None


@dataclass(frozen=True)
class Indicator:
    label: str
    amount: ExactAmount | None
    coverage: Coverage
    knowledge: Knowledge
    formula: str
    participants: tuple[FactEvidence, ...]
    evidence: tuple[str, ...]
    reason: str


@dataclass(frozen=True)
class Reconstruction:
    scope: Scope
    period: Month | None
    parts: tuple[Part, ...]
    independent_extras: tuple[FactEvidence, ...]
    fixed: Indicator
    annual: Indicator
    monthly: Indicator
    earnings: Diagnostic
    functional_exhaustive: bool
    payment_mode: PaymentMode
    issues: tuple[str, ...]
    contracts: tuple[FixedContract | PaymentContract | AnnualContract, ...]


def _amount(f: FactEvidence | None) -> Decimal | None:
    if (
        f
        and f.fact.value.state == ValueState.PRESENT
        and isinstance(f.fact.value.value, ExactDecimal)
    ):
        return f.fact.value.value.to_decimal()
    return None


def _month(value: Month) -> bool:
    return (
        len(value) == 2
        and all(type(x) is int for x in value)
        and 1 <= value[0] <= 9999
        and 1 <= value[1] <= 12
    )


def _period(e: ExtractionConcepts) -> Month | None:
    values = []
    for name in ("anio", "mes"):
        fs = [f for f in e.facts if f.fact.fact_key in ("nomina." + name, "payload/" + name)]
        if len(fs) != 1 or fs[0].fact.value.state != ValueState.PRESENT:
            return None
        v = fs[0].fact.value.value
        if isinstance(v, ExactDecimal):
            d = v.to_decimal()
            if d != d.to_integral_value():
                return None
            values.append(int(d))
        elif isinstance(v, str) and v.isascii() and v.isdigit():
            values.append(int(v))
        else:
            return None
    p = (values[0], values[1])
    return p if _month(p) else None


def _valid(e: ExtractionConcepts, evidence: ContractEvidence) -> bool:
    return bool(
        evidence.reference.strip()
        and evidence.contract_version.strip()
        and evidence.scope == scope_for(e)
        and evidence.period == _period(e)
        and e.content_hash
        and e.content_hash == canonical_sha256({f.fact.fact_key: f.fact.value for f in e.facts})
    )


def _sum(terms: tuple[tuple[Decimal, int], ...]) -> Decimal:
    """Finite monetary values: integer coefficient arithmetic independent of context."""
    scale = max(max(0, -int(v.as_tuple().exponent)) for v, _ in terms)
    total = 0
    for value, count in terms:
        t = value.as_tuple()
        coefficient = int("".join(map(str, t.digits))) * (-1 if t.sign else 1)
        total += coefficient * 10 ** (scale + int(t.exponent)) * count
    return Decimal((int(total < 0), tuple(map(int, str(abs(total)))), -scale))


def _bucket(c: ClassifiedConcept) -> Bucket:
    if c.arrears is True or c.function == Function.ADJUSTMENT:
        return Bucket.ADJUSTMENT
    return {
        Function.FIXED: Bucket.FIXED_CANDIDATE,
        Function.COMPLEMENT: Bucket.FIXED_CANDIDATE,
        Function.EXTRA: Bucket.EXTRA,
        Function.PRORATION: Bucket.PRORATION,
        Function.BONUS: Bucket.VARIABLE,
        Function.UNKNOWN: Bucket.UNKNOWN,
    }.get(c.function, Bucket.OTHER)


def _unavailable(label: str, reason: str, parts: tuple[FactEvidence, ...] = ()) -> Indicator:
    return Indicator(
        label,
        None,
        Coverage.PARTIAL if parts else Coverage.UNAVAILABLE,
        Knowledge.UNDETERMINABLE,
        "",
        parts,
        (),
        reason,
    )


def reconstruct(
    e: ExtractionConcepts,
    fixed: FixedContract | None = None,
    payment: PaymentContract | None = None,
    annual: AnnualContract | None = None,
) -> Reconstruction:
    """One diagnostic scenario per extraction, never a consolidated version selection.

    No production contract is inferred or activated here. Components remain useful
    even without accounting completeness. A scalar total is never added to rows.
    """
    accounting = diagnose_breakdown(e)
    earnings = accounting.diagnostics[0]
    classification = classify_extraction(e)
    conflict = any(d.status == Status.CONFLICT for d in accounting.diagnostics)
    parts = (
        tuple(
            Part(c, _bucket(c), _amount(c.source.get("importe")))
            for c in classification.concepts
            if c.nature == Nature.EARNING
        )
        if not conflict
        else ()
    )
    extras = (
        tuple(
            r.source for r in classification.references if r.function == Function.INDEPENDENT_EXTRA
        )
        if not conflict
        else ()
    )
    candidates = tuple(
        p.source.source.get("importe") for p in parts if p.bucket == Bucket.FIXED_CANDIDATE
    )
    candidate_facts = tuple(f for f in candidates if f is not None)
    fixed_result = _unavailable(
        "Fijo ordinario del periodo",
        "Componentes identificados no acreditan cobertura del fijo ni periodicidad.",
        candidate_facts,
    )
    annual_result = _unavailable(
        "Fijo anual equivalente", "Faltan contratos de cobertura, modalidad y equivalencia anual."
    )
    monthly_result = _unavailable(
        "Fijo mensual equivalente en 12 mensualidades", annual_result.reason
    )
    issues = list(classification.issues)
    if conflict:
        issues.append("Conflicto de procedencia: no se proyectan partidas.")
    selected: tuple[Part, ...] = ()
    if fixed:
        selected = tuple(p for p in parts if p.source.source.occurrence in fixed.occurrences)
        reason = ""
        units = {
            amount_fact.fact.value.currency
            for p in selected
            if (amount_fact := p.source.source.get("importe")) is not None
        }
        if conflict or not _valid(e, fixed.evidence):
            reason = "Contrato incompatible con identidad, contenido o periodo documental."
        elif (
            len(types := [f for f in e.facts if f.fact.fact_key in ("nomina.tipo", "payload/tipo")])
            != 1
            or types[0].fact.value.state != ValueState.PRESENT
            or types[0].fact.value.value != "NOMINA_ORDINARIA"
        ):
            reason = "El fijo ordinario requiere tipo documental ordinario inequívoco."
        elif fixed.complete and {
            p.source.source.occurrence for p in parts if p.bucket == Bucket.FIXED_CANDIDATE
        } != set(fixed.occurrences):
            reason = "Cobertura fija incompleta: hay candidatos sin justificar."
        elif (
            not fixed.occurrences
            or len(set(fixed.occurrences)) != len(fixed.occurrences)
            or len(selected) != len(fixed.occurrences)
        ):
            reason = "Ocurrencias ausentes o repetidas en el contrato."
        elif any(
            p.bucket != Bucket.FIXED_CANDIDATE or p.source.arrears is not False or p.amount is None
            for p in selected
        ):
            reason = "Partidas sin naturaleza fija candidata fiable; no se usan bonus, atrasos ni residuos."
        elif not fixed.signed_amounts or not fixed.common_unit or len(units) != 1:
            reason = "Signos o unidad común no acreditados."
        elif fixed.complete and (
            any(p.bucket == Bucket.UNKNOWN for p in parts)
            or any(c.nature == Nature.UNKNOWN for c in classification.concepts)
        ):
            reason = "Partidas de función o sección desconocida impiden acreditar fijo completo."
        if reason:
            fixed_result = _unavailable(fixed_result.label, reason, candidate_facts)
            issues.append(reason)
        else:
            participants = tuple(p.source.source.get("importe") for p in selected)
            fixed_result = Indicator(
                fixed_result.label,
                ExactAmount(_sum(tuple((p.amount, 1) for p in selected if p.amount is not None))),
                Coverage.COMPLETE if fixed.complete else Coverage.PARTIAL,
                Knowledge.CALCULATED,
                "Suma de ocurrencias fijas acreditadas (sin extras, prorratas, bonus ni atrasos)",
                tuple(f for f in participants if f is not None),
                (fixed.evidence.contract_version + ": " + fixed.evidence.reference,),
                "Cobertura del fijo acreditada; no equivale a total cobrado."
                if fixed.complete
                else "Suma parcial acreditada; no es salario fijo total.",
            )
            selected_ids = set(fixed.occurrences)
            parts = tuple(
                Part(
                    p.source,
                    Bucket.FIXED if p.source.source.occurrence in selected_ids else p.bucket,
                    p.amount,
                )
                for p in parts
            )
    mode = PaymentMode.UNKNOWN
    if payment:
        mode = (
            payment.mode
            if payment.accredited and _valid(e, payment.evidence)
            else PaymentMode.DECLARED
        )
    if annual:
        reason, amount, support, formula = _annual(e, parts, fixed, fixed_result, payment, annual)
        if amount is not None:
            evidence = (
                annual.evidence.contract_version + ": " + annual.evidence.reference,
                payment.evidence.reference if payment else "",
                *fixed_result.evidence,
            )
            annual_result = Indicator(
                annual_result.label,
                ExactAmount(amount),
                Coverage.COMPLETE,
                Knowledge.CALCULATED,
                formula,
                support,
                evidence,
                "Equivalente de la estructura vigente; no es el total cobrado en un ejercicio.",
            )
            monthly_result = Indicator(
                monthly_result.label,
                ExactAmount(amount, 12),
                Coverage.COMPLETE,
                Knowledge.CALCULATED,
                "(" + formula + ") / 12",
                support,
                evidence,
                annual_result.reason,
            )
        else:
            annual_result = _unavailable(annual_result.label, reason)
            monthly_result = _unavailable(monthly_result.label, reason)
    exhaustive = (
        bool(parts)
        and earnings.status == Status.RECONCILED
        and all(
            p.bucket not in (Bucket.UNKNOWN, Bucket.FIXED_CANDIDATE) and p.amount is not None
            for p in parts
        )
    )
    return Reconstruction(
        scope_for(e),
        _period(e),
        parts,
        extras,
        fixed_result,
        annual_result,
        monthly_result,
        earnings,
        exhaustive,
        mode,
        tuple(issues),
        tuple(c for c in (fixed, payment, annual) if c is not None),
    )


def _annual(
    e: ExtractionConcepts,
    parts: tuple[Part, ...],
    fixed: FixedContract | None,
    fixed_result: Indicator,
    payment: PaymentContract | None,
    annual: AnnualContract,
) -> tuple[str, Decimal | None, tuple[FactEvidence, ...], str]:
    def no(reason: str) -> tuple[str, None, tuple[FactEvidence, ...], str]:
        return reason, None, (), ""

    if (
        not fixed
        or fixed_result.coverage != Coverage.COMPLETE
        or not fixed_result.amount
        or not fixed.full_month
    ):
        return no("Falta cobertura fija completa de una mensualidad acreditada.")
    if (
        not payment
        or not payment.accredited
        or not _valid(e, payment.evidence)
        or payment.mode in (PaymentMode.UNKNOWN, PaymentMode.DECLARED)
    ):
        return no("Modalidad de pago no acreditada; no se asumen 12 ni 14 pagas.")
    if (
        not _valid(e, annual.evidence)
        or not _month(annual.valid_from)
        or not _month(annual.valid_until)
        or not annual.valid_from <= annual.evidence.period <= annual.valid_until
    ):
        return no("Contrato anual fuera del periodo o de la extracción acreditada.")
    if not annual.full_extra_composition:
        return no("Composición completa de extras no acreditada; no se proyectan extras parciales.")
    terms = annual.terms
    if (
        not terms
        or len({t.occurrence for t in terms}) != len(terms)
        or any(type(t.repetitions) is not int or t.repetitions < 1 for t in terms)
    ):
        return no("Términos anuales ausentes, repetidos o multiplicidades inválidas.")
    selected = {p.source.source.occurrence: p for p in parts}
    if any(t.occurrence not in selected for t in terms):
        return no("Términos de otra extracción o ausentes.")
    ordinary = {t.occurrence for t in terms if selected[t.occurrence].bucket == Bucket.FIXED}
    if ordinary != set(fixed.occurrences) or any(
        t.repetitions != 12 for t in terms if t.occurrence in ordinary
    ):
        return no(
            "Se requieren doce mensualidades de la estructura fija explícitamente acreditada."
        )
    allowed = (
        {Bucket.FIXED, Bucket.PRORATION}
        if payment.mode == PaymentMode.PRORATED
        else {Bucket.FIXED, Bucket.EXTRA}
    )
    if any(
        selected[t.occurrence].bucket not in allowed
        or selected[t.occurrence].source.arrears is not False
        or selected[t.occurrence].amount is None
        for t in terms
    ):
        return no("Bonus, atrasos, desconocidos o extras/prorratas incompatibles con la modalidad.")
    nonordinary = [t for t in terms if t.occurrence not in ordinary]
    if payment.mode == PaymentMode.SEPARATE and not nonordinary:
        return no("Falta composición e importe de extras separadas; no se multiplica por 14.")
    if payment.mode == PaymentMode.PRORATED and (
        not nonordinary or any(t.repetitions != 12 for t in nonordinary)
    ):
        return no(
            "Se requieren prorratas acreditadas durante doce mensualidades, sin extras duplicadas."
        )
    support = tuple(selected[t.occurrence].source.source.get("importe") for t in terms)
    evidence = tuple(f for f in support if f is not None)
    if len({f.fact.value.currency for f in evidence}) != 1:
        return no("Unidades monetarias incompatibles.")
    amounts = tuple((selected[t.occurrence].amount, t.repetitions) for t in terms)
    total = _sum(tuple((v, n) for v, n in amounts if v is not None))
    formula = " + ".join(f"{t.repetitions} × [{t.occurrence}]" for t in terms)
    return "", total, evidence, formula


def identified_ordinary(e: ExtractionConcepts) -> Indicator:
    """B2b.3: reviewed ordinary subset, not recurrence or complete fixed coverage.

    The exact B2a tuples identify ordinary salary rows. Pinned B2b.1 contracts
    authorize their signed addition only within reconciled earnings of this
    extraction. No total-minus-exceptions formula, annualization or scalar fallback.
    """
    label = "Ordinario identificado (parcial)"
    r = reconstruct(e)
    types = [f.fact.value for f in e.facts if f.fact.fact_key in ("nomina.tipo", "payload/tipo")]
    if (
        e.extractor_name not in ("InecoParser", "ExcelticParser")
        or len(types) != 1
        or types[0].state != ValueState.PRESENT
        or types[0].value != "NOMINA_ORDINARIA"
        or r.earnings.status != Status.RECONCILED
    ):
        return _unavailable(
            label,
            "Sin contrato ordinario aplicable o devengos no conciliados; consulta las partidas individuales.",
        )
    parts = tuple(
        p for p in r.parts if p.bucket == Bucket.FIXED_CANDIDATE and p.source.arrears is False
    )
    if not parts or any(p.amount is None for p in parts):
        return _unavailable(label, "No hay componentes ordinarios inequívocos con importe fiable.")
    participants = tuple(f for p in parts if (f := p.source.source.get("importe")) is not None)
    return Indicator(
        label,
        ExactAmount(_sum(tuple((p.amount, 1) for p in parts if p.amount is not None))),
        Coverage.PARTIAL,
        Knowledge.CALCULATED,
        "Suma de filas ordinarias identificadas; excluye extras, prorratas, bonus, atrasos y otros conceptos",
        participants,
        ("ordinary-subset/b2b3-v1", r.earnings.contract_reference or ""),
        "Participación contable acreditada; cobertura salarial y periodicidad no acreditadas. No es fijo comparable.",
    )
